// Builds the standalone `incibase` executable:
//   1. bundles the framework (+ zod) into dist/runtime/ with shared chunks,
//   2. embeds those files and the dashboard HTML so `incibase build` can
//      compile user apps offline,
//   3. compiles src/cli.ts into dist/incibase (or dist/incibase-<target>).
//
// Usage: bun scripts/build-binary.ts [--target bun-linux-x64 ...]
import { readdirSync, rmSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import { parseArgs } from "node:util";

const root = join(import.meta.dir, "..");
const runtimeDir = join(root, "dist", "runtime");
const embeddedFile = join(root, "src", "engine", "embedded.ts");
const { values } = parseArgs({ options: { target: { type: "string", multiple: true } } });

const placeholder = await Bun.file(embeddedFile).text();

rmSync(runtimeDir, { recursive: true, force: true });
const runtime = await Bun.build({
  entrypoints: ["index", "server", "client", "cli"].map((n) => join(root, "src", `${n}.ts`)).concat(join(import.meta.dir, "runtime", "zod.ts")),
  outdir: runtimeDir,
  target: "bun",
  format: "esm",
  splitting: true,
  minify: true,
  naming: { entry: "[name].[ext]", chunk: "chunk-[hash].[ext]" },
});
if (!runtime.success) throw new AggregateError(runtime.logs, "runtime bundle failed");

// The dashboard as one self-contained HTML file, served by every build.
const { buildDashboardHtml } = await import("../src/engine/dashboard.ts");
writeFileSync(join(runtimeDir, "dashboard.html"), await buildDashboardHtml());

const files = readdirSync(runtimeDir).filter((f) => f.endsWith(".js") || f.endsWith(".html"));
writeFileSync(
  embeddedFile,
  `// Generated by scripts/build-binary.ts; restored to a placeholder afterwards.\n` +
    files.map((f, i) => `import f${i} from ${JSON.stringify(relative(join(root, "src", "engine"), join(runtimeDir, f)))} with { type: "file" };\n`).join("") +
    `export const embeddedRuntime: Record<string, string> = {\n` +
    files.map((f, i) => `  ${JSON.stringify(f)}: f${i},\n`).join("") +
    `};\n`,
);

try {
  for (const target of values.target ?? [undefined]) {
    const outfile = join(root, "dist", target ? `incibase-${target.replace(/^bun-/, "")}` : "incibase");
    const result = await Bun.build({
      entrypoints: [join(root, "src", "cli.ts")],
      // Never read bunfig.toml (its preload runs code) or .env from the cwd: `sudo incibase …` keeps the cwd,
      // often the login user's home, so either would let that user's files steer a root process.
      compile: { outfile, autoloadBunfig: false, autoloadDotenv: false, ...(target ? { target: target as any } : {}) },
      minify: true,
    });
    if (!result.success) throw new AggregateError(result.logs, `compile failed for ${target ?? "host"}`);
    console.log(`built ${relative(process.cwd(), outfile)} (${(Bun.file(outfile).size / 1e6).toFixed(1)} MB)`);
  }
} finally {
  writeFileSync(embeddedFile, placeholder);
}
